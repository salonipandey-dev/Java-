public class Halfpyramid {
    public static void main(String args[])
    {
        int n=9;
        for(int line=n;line>=1;line--)
        {
            for(int num=n;num>=line;num--)
            {
                System.out.print(num);
            }
            
      System.out.println();  
    
    }
        
}
}
