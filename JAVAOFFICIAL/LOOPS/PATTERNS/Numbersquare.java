package JAVAOFFICIAL.LOOPS.PATTERNS;

public class Numbersquare {
    public static void main(String args[]){
        int num =5;
        for(int i =1;i<=num;i++){
            for(int j =1; j<=num; j++){
                System.out.print("1 ");
            }
            System.out.println(" ");
        }
    }
    
}
